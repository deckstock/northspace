    // Platform Deep Wipe (Wipes all videos, categories, collections, DMCA, logs, watch tracking)
    wipeEntirePlatform(wipeCategories = true) {
      activeCatalog = [];
      if (Array.isArray(window.NORTHSPACE_FEED)) {
        window.NORTHSPACE_FEED = [];
      }
      if (wipeCategories) {
        activeCategories = [];
      }
      activeCollections = [];
      activeDMCA = [];
      activeLogs = [];
      activeHomepageConfig = JSON.parse(JSON.stringify(DEFAULT_HOMEPAGE_CONFIG));

      try {
        localStorage.setItem(STORAGE_KEY_CATALOG, JSON.stringify([]));
        localStorage.setItem(STORAGE_KEY_COLLECTIONS, JSON.stringify([]));
        localStorage.setItem(STORAGE_KEY_DMCA, JSON.stringify([]));
        localStorage.setItem(STORAGE_KEY_LOGS, JSON.stringify([]));
        localStorage.setItem(STORAGE_KEY_HOMEPAGE, JSON.stringify(DEFAULT_HOMEPAGE_CONFIG));

        if (wipeCategories) {
          localStorage.setItem(STORAGE_KEY_CATEGORIES, JSON.stringify([]));
        }

        localStorage.removeItem(STORAGE_KEY_DRAFT);
        localStorage.removeItem('aether_continue_watching');
        localStorage.removeItem('aether_last_category');
      } catch (e) {
        console.error('Failed to wipe platform storage:', e);
      }

      return true;
    }
