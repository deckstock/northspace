  function unescapeEntities(str) {
    if (!str) return '';
    return String(str)
      .replace(/&amp;/g, '&')
      .replace(/&#x27;|&#27;|&apos;/g, "'")
      .replace(/&quot;/g, '"')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>');
  }

  function normalizeCatalogItems(arr) {
    if (!Array.isArray(arr)) return [];
    return arr.map((item, i) => {
      const itemTitle = unescapeEntities(item.title || `Video Reel #${i + 1}`);
      const itemCat = (item.category && item.category !== 'all') ? item.category : 'cinema';
      const itemTags = Array.isArray(item.tags)
        ? item.tags
        : (item.tags ? String(item.tags).split(',').map(t => t.trim().toLowerCase()).filter(Boolean) : ['stream', itemCat]);

      return {
        id: item.id || `vid_ext_${i + 1}_${Math.floor(10000 + Math.random() * 90000)}`,
        slug: item.slug || generateSlug(itemTitle),
        title: itemTitle,
        category: itemCat,
        tags: itemTags.length > 0 ? itemTags : ['stream', itemCat],
        duration: parseInt(item.duration, 10) || 180,
        views: parseInt(item.views, 10) || 0,
        daysAgo: parseInt(item.daysAgo, 10) || 0,
        likes: parseInt(item.likes, 10) || 0,
        status: item.status || 'published',
        playbackType: item.embedUrl ? 'embed' : 'stream',
        thumb: item.thumb || PLACEHOLDER_THUMB,
        fallbackThumb: item.fallbackThumb || "",
        embedUrl: item.embedUrl || "",
        videoUrl: item.videoUrl || "",
        description: unescapeEntities(item.description) || "Video stream asset.",
        updatedAt: item.updatedAt || new Date().toISOString()
      };
    });
  }

  /**
   * Universal Catalog Parser
   */
  function parseUniversalCatalog(rawInput) {
    if (!rawInput) return [];
    if (Array.isArray(rawInput)) return normalizeCatalogItems(rawInput);
    if (typeof rawInput === 'object') {
      if (Array.isArray(rawInput.catalog)) return normalizeCatalogItems(rawInput.catalog);
      if (Array.isArray(rawInput.videos)) return normalizeCatalogItems(rawInput.videos);
      return normalizeCatalogItems([rawInput]);
    }

    const text = String(rawInput).trim();
    if (!text) return [];

    try {
      const parsed = JSON.parse(text);
      if (Array.isArray(parsed)) return normalizeCatalogItems(parsed);
      if (parsed && Array.isArray(parsed.catalog)) return normalizeCatalogItems(parsed.catalog);
      if (parsed && Array.isArray(parsed.videos)) return normalizeCatalogItems(parsed.videos);
      if (parsed && typeof parsed === 'object') return normalizeCatalogItems([parsed]);
    } catch (e) {}

    let blocks = [];
    if (/===+\s*Video\s+Record/i.test(text)) {
      blocks = text.split(/(?====+\s*Video\s+Record)/i);
    } else if (/------------------------------------------------------------/.test(text)) {
      blocks = text.split(/------------------------------------------------------------+/);
    } else if (/\n\s*\n/.test(text)) {
      blocks = text.split(/\n\s*\n+/);
    } else {
      blocks = [text];
    }

    const list = [];
    let idx = 1;

    for (let i = 0; i < blocks.length; i++) {
      const block = blocks[i].trim();
      if (!block) continue;

      const getVal = (pattern) => {
        const m = block.match(pattern);
        if (!m || !m[1]) return '';
        const v = unescapeEntities(m[1].trim());
        return (v === 'N/A' || v.toLowerCase() === 'none' || v.toLowerCase() === 'null') ? '' : v;
      };

      const title = getVal(/(?:^|\n)\s*Title\s*:\s*(.+)/i);
      const directStream = getVal(/(?:^|\n)\s*Direct\s+Stream\s*:\s*(.+)/i);
      const embedLink = getVal(/(?:^|\n)\s*Embed\s+Link\s*:\s*(.+)/i);
      const thumbnail = getVal(/(?:^|\n)\s*Thumbnail\s*:\s*(.+)/i);
      const description = getVal(/(?:^|\n)\s*Description\s*:\s*(.+)/i);
      const sourceUrl = getVal(/(?:^|\n)\s*Source\s+URL\s*:\s*(.+)/i);
      const category = getVal(/(?:^|\n)\s*Category\s*:\s*(.+)/i);

      if (!title && !directStream && !embedLink && !sourceUrl) {
        continue;
      }

      const duration = Math.floor(Math.random() * 180) + 120;
      const views = Math.floor(Math.random() * 75000) + 2500;
      const daysAgo = Math.floor(Math.random() * 14) + 1;
      const likes = Math.floor(views * (0.03 + Math.random() * 0.04));

      list.push({
        id: `vid_ext_${idx}_${Math.floor(10000 + Math.random() * 90000)}`,
        slug: generateSlug(title || `Extracted Video #${idx}`),
        title: title || `Extracted Video #${idx}`,
        category: category || 'cinema',
        tags: ['stream', 'external', 'curated'],
        duration: duration,
        views: views,
        daysAgo: daysAgo,
        likes: likes,
        status: "published",
        playbackType: embedLink ? "embed" : "stream",
        thumb: thumbnail || PLACEHOLDER_THUMB,
        fallbackThumb: '',
        embedUrl: embedLink || '',
        videoUrl: directStream || (embedLink ? '' : sourceUrl) || '',
        description: description || 'Direct extracted media stream asset.',
        updatedAt: new Date().toISOString()
      });
      idx++;
    }

    return list;
  }

  // --- Display Helpers ---
  function formatTime(sec) {
    if (isNaN(sec) || sec === Infinity) return '00:00';
    const m = Math.floor(sec / 60);
    const s = Math.floor(sec % 60);
    return `${m.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')}`;
  }

  function formatViews(num) {
    if (num >= 1000000) return (num / 1000000).toFixed(1) + 'M views';
    if (num >= 1000) return (num / 1000).toFixed(1) + 'K views';
    return (num || 0) + ' views';
  }

  function generateSlug(text) {
    return String(text || '')
      .toLowerCase()
      .trim()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') || `item-${Date.now()}`;
  }

