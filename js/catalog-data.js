  function loadActiveCategories() {
    let list = [];
    try {
      const saved = localStorage.getItem(STORAGE_KEY_CATEGORIES);
      if (saved !== null) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed)) {
          // Automatic purge: if browser contains previous hardcoded sample categories, wipe them cleanly
          const isLegacy = parsed.some(c => c && ['cinema', 'docs', 'trending', 'leaks', 'experimental', 'shorts', 'curated'].includes(c.slug));
          if (isLegacy) {
            localStorage.setItem(STORAGE_KEY_CATEGORIES, '[]');
          } else {
            list = parsed;
          }
        }
      }
    } catch (e) {
      console.warn('Failed to load categories from localStorage:', e);
    }

    // Auto-discover and register categories from live feed (if available)
    const feed = Array.isArray(window.NORTHSPACE_FEED) ? window.NORTHSPACE_FEED : [];
    if (feed.length > 0) {
      const knownSlugs = new Set(list.map(c => c.slug));
      let hasNewCat = false;
      feed.forEach(v => {
        const catSlug = v.category;
        if (catSlug && catSlug !== 'all' && !knownSlugs.has(catSlug)) {
          const catName = catSlug.replace(/[-_]/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
          list.push({
            id: `cat_${catSlug}`,
            name: catName,
            slug: catSlug,
            image: v.thumb || '',
            description: `Curated ${catName} stream assets`,
            visible: true,
            showOnHome: true,
            order: list.length + 1
          });
          knownSlugs.add(catSlug);
          hasNewCat = true;
        }
      });
      if (hasNewCat) {
        saveCategoriesToStorage(list);
      }
    }

    return list.map((c, idx) => ({
      visible: c.visible !== false,
      showOnHome: c.showOnHome !== false,
      order: typeof c.order === 'number' ? c.order : (idx + 1),
      ...c
    })).sort((a, b) => (a.order || 0) - (b.order || 0));
  }

