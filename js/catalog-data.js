    // Broken Link Detector & System Health
    scanCatalogHealth() {
      const brokenVideos = [];
      const missingThumbnails = [];
      const insecureUrls = [];
      const missingCategory = [];

      activeCatalog.forEach(v => {
        const hasEmbed = !!(v.embedUrl && v.embedUrl.trim());
        const hasStream = !!(v.videoUrl && v.videoUrl.trim());
        if (!hasEmbed && !hasStream) {
          brokenVideos.push(v);
        }
        if (!v.thumb || !v.thumb.trim()) {
          missingThumbnails.push(v);
        }
        if ((v.embedUrl && v.embedUrl.startsWith('http://')) || (v.videoUrl && v.videoUrl.startsWith('http://'))) {
          insecureUrls.push(v);
        }
        if (!v.category || v.category === 'all') {
          missingCategory.push(v);
        }
      });

      const total = activeCatalog.length || 1;
      const healthyCount = total - brokenVideos.length;
      const healthScore = activeCatalog.length === 0 ? 100 : Math.max(0, Math.min(100, Math.round((healthyCount / total) * 100)));

      return {
        totalScanned: activeCatalog.length,
        healthyCount: healthyCount,
        brokenVideos: brokenVideos,
        missingThumbnails: missingThumbnails,
        insecureUrls: insecureUrls,
        missingCategory: missingCategory,
        healthScore: healthScore
      };
    },

    // Duplicate Entry Detector
    detectDuplicates() {
      const embedMap = new Map();
      const streamMap = new Map();
      const titleMap = new Map();

      const dupEmbeds = [];
      const dupStreams = [];
      const dupTitles = [];

      activeCatalog.forEach(v => {
        if (v.embedUrl) {
          const u = v.embedUrl.trim().toLowerCase();
          if (embedMap.has(u)) {
            dupEmbeds.push({ original: embedMap.get(u), duplicate: v, url: v.embedUrl });
          } else {
            embedMap.set(u, v);
          }
        }
        if (v.videoUrl) {
          const s = v.videoUrl.trim().toLowerCase();
          if (streamMap.has(s)) {
            dupStreams.push({ original: streamMap.get(s), duplicate: v, url: v.videoUrl });
          } else {
            streamMap.set(s, v);
          }
        }
        if (v.title) {
          const t = v.title.trim().toLowerCase();
          if (titleMap.has(t)) {
            dupTitles.push({ original: titleMap.get(t), duplicate: v, title: v.title });
          } else {
            titleMap.set(t, v);
          }
        }
      });

      return {
        duplicateEmbeds: dupEmbeds,
        duplicateStreams: dupStreams,
        duplicateTitles: dupTitles,
        totalDuplicates: dupEmbeds.length + dupStreams.length + dupTitles.length
      };
    },

