    addCollection(data) {
      const newColl = {
        id: `coll_${Date.now()}_${Math.floor(100 + Math.random() * 900)}`,
        name: data.name || 'Untitled Collection',
        slug: data.slug || generateSlug(data.name || 'collection'),
        description: data.description || '',
        image: data.image || '',
        videoIds: Array.isArray(data.videoIds) ? data.videoIds : [],
        isPublic: data.isPublic !== false,
        order: activeCollections.length + 1,
        createdAt: new Date().toISOString()
      };
      activeCollections.push(newColl);
      saveCollectionsToStorage(activeCollections);
      this.logActivity('Collection Created', `Created collection "${newColl.name}" with ${newColl.videoIds.length} videos.`, 'collections');
      return newColl;
    },

    updateCollection(id, updates) {
      const idx = activeCollections.findIndex(c => c.id === id);
      if (idx !== -1) {
        activeCollections[idx] = { ...activeCollections[idx], ...updates, updatedAt: new Date().toISOString() };
        saveCollectionsToStorage(activeCollections);
        this.logActivity('Collection Updated', `Updated collection "${activeCollections[idx].name}".`, 'collections');
        return activeCollections[idx];
      }
      return null;
    },

    deleteCollection(id) {
      const coll = activeCollections.find(c => c.id === id);
      activeCollections = activeCollections.filter(c => c.id !== id);
      saveCollectionsToStorage(activeCollections);
      if (coll) {
        this.logActivity('Collection Deleted', `Deleted collection "${coll.name}".`, 'collections');
      }
      return true;
    },

